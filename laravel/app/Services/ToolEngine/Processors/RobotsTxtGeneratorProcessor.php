<?php

namespace App\Services\ToolEngine\Processors;

use App\Models\Tool;

class RobotsTxtGeneratorProcessor extends BaseToolProcessor
{
    public function getSlug(): string
    {
        return 'robots-txt-generator';
    }

    public function getValidationRules(): array
    {
        return [
            'user_agent' => 'nullable|string|max:100',
            'disallow_paths' => 'nullable|array',
            'disallow_paths.*' => 'string|max:255',
            'allow_paths' => 'nullable|array',
            'allow_paths.*' => 'string|max:255',
            'sitemap_url' => 'nullable|url|max:255',
            'crawl_delay' => 'nullable|integer|min:0|max:60',
        ];
    }

    public function process(array $input, Tool $tool): array
    {
        return $this->executeSafely(function () use ($input) {
            $ua = $input['user_agent'] ?? '*';
            $disallow = $input['disallow_paths'] ?? ['/admin/', '/api/', '/temp/'];
            $allow = $input['allow_paths'] ?? ['/'];
            $sitemap = $input['sitemap_url'] ?? null;
            $crawlDelay = $input['crawl_delay'] ?? null;

            $lines = [];
            $lines[] = "# Generated by ToolsHub robots.txt generator";
            $lines[] = "User-agent: {$ua}";

            if (!empty($crawlDelay)) {
                $lines[] = "Crawl-delay: {$crawlDelay}";
            }

            foreach ($disallow as $p) {
                if (!empty(trim($p))) {
                    $lines[] = "Disallow: " . trim($p);
                }
            }

            foreach ($allow as $p) {
                if (!empty(trim($p))) {
                    $lines[] = "Allow: " . trim($p);
                }
            }

            if (!empty($sitemap)) {
                $lines[] = "";
                $lines[] = "Sitemap: {$sitemap}";
            }

            $content = implode("\n", $lines);

            return [
                'output' => [
                    'robots_txt' => $content,
                    'line_count' => count($lines),
                ],
                'download_token' => null,
            ];
        });
    }
}
